#!/usr/bin/env python3
"""Regenerate per-stroke vector paths for the KIRITSU title intro.

Inputs (locked since 2026-11-15):
  - public/kanji/ou-guilv-tight.svg  (Yuji Boku Light cut glyph, generated by
    tools/gen-title-svg.py)
  - tools/title-plan.json            (stroke centre lines + per-point cover
    widths, exported once from the title renderer; see docs/TITLE_KANJI.md)
Output:
  - src/ui/title-stroke-paths.ts     (20 disjoint vector paths + sweep radii)

Each stroke directory is split from the exact glyph with pathops boolean
partition: tube_i = union of circles along the centreline; parts are assigned
in writing order and the leftover is appended to the last stroke, so the union
of all 20 paths equals the glyph exactly (no cross-bleed, no ghosting).

Dev-only: needs fontTools + skia-pathops (the PDF toolchain env has them).
  PYTHONPATH=<pdfdeps> python3 tools/gen-title-strokes.py
"""
import sys, json, re, math
sys.path.insert(0,'/home/jung/ai_station/sandbox/.pdfdeps')
import pathops
from fontTools.svgLib.path import parse_path

svg=open('public/kanji/ou-guilv-tight.svg',encoding='utf-8').read()
ds=[m.group(2) for m in re.finditer(r'<g transform="([^"]+)"[^>]*><path d="([^"]+)"',svg)]
print('glyph paths',len(ds))
glyph=pathops.Path()
for d in ds:
    parse_path(d, glyph.getPen())
glyph.simplify()

plan=json.load(open('tools/title-plan.json'))
geoms=plan['geoms']; print('strokes',len(geoms))
# 빌드된 스켈레톤 순서 = KanjiVG 순서와 동일해야 함(현재 파일 순서)
# 튜브(획 소유 영역) = 중심선 주변 반경(획별 최대 cover + margin) 원판 합집합
shapes=[]
radii=[]
remaining=pathops.Path(); remaining.addPath(glyph)
# 획별 disjoint 분할: writing order대로 튜브 ∩ 남은 잉크를 떼어낸다.
# 마지막에 남은 조각은 마지막 획에 귀속 → 20개 패스의 union = glyph 정확히.
for i,g in enumerate(geoms):
    pts=g['pts']; cover=g['cover']
    tube=pathops.Path()
    for pt,cov in zip(pts,cover):
        x=float(pt['x']); y=float(pt['y']); r=float(cov)+4.0
        c=pathops.Path(); k=0.5522847498
        c.moveTo(x+r,y)
        c.cubicTo(x+r,y+k*r,x+k*r,y+r,x,y+r)
        c.cubicTo(x-k*r,y+r,x-r,y+k*r,x-r,y)
        c.cubicTo(x-r,y-k*r,x-k*r,y-r,x,y-r)
        c.cubicTo(x+k*r,y-r,x+r,y-k*r,x+r,y)
        c.close()
        tube=pathops.op(tube,c,pathops.PathOp.UNION)
    part=pathops.op(remaining,tube,pathops.PathOp.INTERSECTION)
    if part.area < 1:
        part=pathops.op(glyph,tube,pathops.PathOp.INTERSECTION)
    shapes.append(part)
    remaining=pathops.op(remaining,part,pathops.PathOp.DIFFERENCE)
    radii.append(round(max(cover)+4,1))
print('leftover area',round(remaining.area,1),'glyph area',round(glyph.area,1))
if remaining.area>0.5:
    shapes[-1]=pathops.op(shapes[-1],remaining,pathops.PathOp.UNION)
    print('assigned leftover to last')

class Pen:
    def __init__(self): self.parts=[]; self.cur=''
    def _pt(self,p): return f"{p[0]:.1f} {p[1]:.1f}"
    def moveTo(self,p): 
        if self.cur: self.parts.append(self.cur)
        self.cur='M'+self._pt(p)
    def lineTo(self,p): self.cur+='L'+self._pt(p)
    def qCurveTo(self,*pts):
        pts=[p for p in pts if p is not None]
        # pathops can emit multi-point qCurveTo: implied on-curve points are
        # midpoints between consecutive controls. SVG Q only takes one control.
        while len(pts)>2:
            c=pts[0]; nxt=pts[1]
            end=((c[0]+nxt[0])/2,(c[1]+nxt[1])/2)
            self.cur+='Q'+self._pt(c)+' '+self._pt(end)
            pts=pts[1:]
        self.cur+='Q'+self._pt(pts[0])+' '+self._pt(pts[1])
    def curveTo(self,*pts): self.cur+='C'+' '.join(self._pt(p) for p in pts)
    def closePath(self): self.cur+='Z'
    def endPath(self):
        if self.cur: self.parts.append(self.cur); self.cur=''
    def get(self):
        if self.cur: self.parts.append(self.cur); self.cur=''
        return ''.join(self.parts)

out=[]
for p in shapes:
    p.simplify(); p.convertConicsToQuads()
    pen=Pen(); p.draw(pen); out.append(pen.get())
print('total d bytes',sum(len(s) for s in out),'max',max(len(s) for s in out))
json.dump({'paths':out,'radii':radii,'glyphArea':glyph.area,'inkPixels':plan['inkPixels']},open('/tmp/stroke-paths.json','w'))
# 검증용 오버레이 SVG
cols=['#ff6b8a','#5fe0ff','#ffd166','#8dff9e','#c39bff','#ff9f43','#e77fff','#6bffd8']
parts=[]
for i,d in enumerate(out):
    parts.append(f'<path d="{d}" fill="{cols[i%len(cols)]}" fill-opacity=".65"/>')
    # 중심선 번호
    g=geoms[i]; p=g['pts'][0]; px=float(p['x']); py=float(p['y'])
    parts.append('<text x="%.0f" y="%.0f" font-size="9" fill="#fff">%d</text>' % (px, py, i+1))
open('/tmp/stroke-overlay.html','w').write('<!doctype html><html><body style="margin:0;background:#040b08"><svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 300" width="1200" height="600">'+''.join(parts)+'</svg></body></html>')
print('done')

mod = []
mod.append("// GENERATED by tools/gen-title-strokes.py — do not hand-edit.")
mod.append("// 20 per-stroke vector paths (viewBox 600×300) clipped from the Yuji Boku Light")
mod.append("// title glyph by tools/gen-title-strokes.py (pathops boolean partition).")
mod.append("// Stroke order follows KIRITSU_TITLE_STROKES / KanjiVG.")
mod.append("export const KIRITSU_TITLE_STROKE_PATHS: string[] = [")
for d in out:
    mod.append("  " + repr(d) + ",")
mod.append("];")
mod.append("export const KIRITSU_TITLE_STROKE_RADII: number[] = " + repr(radii) + ";")
mod.append("export const KIRITSU_TITLE_INK_PIXELS = " + str(plan['inkPixels']) + ";")
open('src/ui/title-stroke-paths.ts','w').write("\n".join(mod)+"\n")
print('wrote src/ui/title-stroke-paths.ts')
